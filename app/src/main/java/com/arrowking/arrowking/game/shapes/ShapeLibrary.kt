    fun shapeForLevel(level: Int, targetMaxSide: Int, seed: Long): LevelMask {
        val isBoss = level % 25 == 0
        val rng = Random(seed xor 0x517CC1B727220A95L)

        // Never repeat the same shape in two consecutive levels
        val prevBaseIndex = if (level > 1) templateIndexForLevel(level - 1) else -1
        val curIndex = templateIndexForLevel(level, avoidIndex = prevBaseIndex)

        // After level 10, mix in ~25% procedural symmetric blobs for infinite fresh silhouettes (never on boss levels)
        val useProceduralBlob = !isBoss && level > 10 && (rng.nextInt(4) == 0)

        val tier = when {
            targetMaxSide <= 21 -> MaskSizeTier.SMALL
            targetMaxSide <= 30 -> MaskSizeTier.MEDIUM
            else -> MaskSizeTier.LARGE
        }

        if (useProceduralBlob) {
            return buildProceduralSymmetricBlob(
                level = level,
                targetMaxSide = targetMaxSide,
                rng = rng
            )
        }

        val template = templates[curIndex]
        val mirrorX = rng.nextBoolean()
        val rotSteps = if (template.allowRotate90) rng.nextInt(4) else 0
        return buildMaskFromTemplate(
            template = template,
            targetMaxSide = max(targetMaxSide, tier.scaleTarget.coerceAtMost(targetMaxSide)),
            mirrorX = mirrorX,
            rotSteps = rotSteps,
            isBoss = isBoss
        )
    }

    private fun templateIndexForLevel(level: Int, avoidIndex: Int = -1): Int {
        val isBoss = level % 25 == 0
        val pool = if (isBoss) {
            templates.indices.filter { templates[it].isBossEligible }
        } else {
            templates.indices.toList()
        }
        // Deterministic mixed index
        val mixed = ((level * 2654435761L) ushr 16).toInt() and 0x7FFFFFFF
        var idx = pool[mixed % pool.size]
        if (idx == avoidIndex && pool.size > 1) {
            idx = pool[(mixed + 1) % pool.size]
        }
        return idx
    }

    fun buildMaskFromTemplate(
        template: ShapeTemplate,
        targetMaxSide: Int,
        mirrorX: Boolean = false,
        rotSteps: Int = 0,
        isBoss: Boolean = false
    ): LevelMask {
        val rawH = template.rows.size
        val rawW = template.rows.maxOf { it.length }
        var grid = Array(rawH) { y ->
            BooleanArray(rawW) { x ->
                template.rows[y].getOrElse(x) { '.' } == '#'
            }
        }

        if (mirrorX) {
            grid = Array(rawH) { y ->
                BooleanArray(rawW) { x -> grid[y][rawW - 1 - x] }
            }
        }

        repeat(rotSteps % 4) {
            val h = grid.size
            val w = grid[0].size
            grid = Array(w) { y ->
                BooleanArray(h) { x -> grid[h - 1 - x][y] }
            }
        }

        val srcH = grid.size
        val srcW = grid[0].size
        val scale = targetMaxSide.toFloat() / max(srcW, srcH).toFloat()
        val outW = max(10, (srcW * scale).toInt())
        val outH = max(10, (srcH * scale).toInt())

        val scaled = Array(outH) { y ->
            val sy = min(srcH - 1, (y * srcH) / outH)
            BooleanArray(outW) { x ->
                val sx = min(srcW - 1, (x * srcW) / outW)
                grid[sy][sx]
            }
        }

        val cleaned = keepLargestComponentAndFillPinholes(scaled, outW, outH)
        val cells = HashSet<Cell>(outW * outH)
        for (y in 0 until outH) {
            for (x in 0 until outW) {
                if (cleaned[y][x]) cells.add(Cell(x, y))
            }
        }

        return LevelMask(
            shapeId = template.id,
            shapeName = template.name,
            width = outW,
            height = outH,
            cells = cells,
            isBoss = isBoss
        )
    }

    fun buildProceduralSymmetricBlob(
        level: Int,
        targetMaxSide: Int,
        rng: Random
    ): LevelMask {
        val w = targetMaxSide
        val h = (targetMaxSide * (0.85f + rng.nextFloat() * 0.25f)).toInt().coerceIn(14, targetMaxSide)
        val grid = Array(h) { BooleanArray(w) }

        val cx = (w - 1) / 2f
        val cy = (h - 1) / 2f
        val numShapes = 3 + rng.nextInt(3)

        // Central spine ellipse so all mirrored lobes stay connected
        val spineRx = w * (0.16f + rng.nextFloat() * 0.10f)
        val spineRy = h * (0.34f + rng.nextFloat() * 0.12f)
        for (y in 0 until h) {
            for (x in 0 until w) {
                val dx = (x - cx) / spineRx
                val dy = (y - cy) / spineRy
                if (dx * dx + dy * dy <= 1.0f) grid[y][x] = true
            }
        }

        repeat(numShapes) {
            val isEllipse = rng.nextBoolean()
            val offsetX = rng.nextFloat() * (w * 0.28f)
            val offsetY = (rng.nextFloat() - 0.5f) * (h * 0.55f)
            val rx = w * (0.14f + rng.nextFloat() * 0.16f)
            val ry = h * (0.14f + rng.nextFloat() * 0.18f)

            for (y in 0 until h) {
                for (x in 0 until w) {
                    val leftDist = if (isEllipse) {
                        val dx = (x - (cx - offsetX)) / rx
                        val dy = (y - (cy + offsetY)) / ry
                        dx * dx + dy * dy <= 1f
                    } else {
                        abs(x - (cx - offsetX)) <= rx && abs(y - (cy + offsetY)) <= ry
                    }
                    val rightDist = if (isEllipse) {
                        val dx = (x - (cx + offsetX)) / rx
                        val dy = (y - (cy + offsetY)) / ry
                        dx * dx + dy * dy <= 1f
                    } else {
                        abs(x - (cx + offsetX)) <= rx && abs(y - (cy + offsetY)) <= ry
                    }
                    if (leftDist || rightDist) {
                        grid[y][x] = true
                    }
                }
            }
        }

        val cleaned = keepLargestComponentAndFillPinholes(grid, w, h)
        val cells = HashSet<Cell>(w * h)
        for (y in 0 until h) {
            for (x in 0 until w) {
                if (cleaned[y][x]) cells.add(Cell(x, y))
            }
        }

        return LevelMask(
            shapeId = "crest_blob_$level",
            shapeName = "Royal Crest",
            width = w,
            height = h,
            cells = cells,
            isBoss = false
        )
    }

    /**
     * Ensures the mask has a single 4-connected component (no disconnected specks)
     * and fills tiny 1-cell enclosed gaps or degree-1 hairline spurs if needed.
     */
    fun keepLargestComponentAndFillPinholes(
        raw: Array<BooleanArray>,
        w: Int,
        h: Int
    ): Array<BooleanArray> {
        val visited = Array(h) { BooleanArray(w) }
        var bestComponent: List<Cell> = emptyList()
        val queue = ArrayDeque<Cell>()

        for (y in 0 until h) {
            for (x in 0 until w) {
                if (raw[y][x] && !visited[y][x]) {
                    val comp = ArrayList<Cell>()
                    queue.add(Cell(x, y))
                    visited[y][x] = true
                    while (queue.isNotEmpty()) {
                        val cur = queue.removeFirst()
                        comp.add(cur)
                        for (dir in Direction.entries) {
                            val nx = cur.x + dir.dx
                            val ny = cur.y + dir.dy
                            if (nx in 0 until w && ny in 0 until h && raw[ny][nx] && !visited[ny][nx]) {
                                visited[ny][nx] = true
                                queue.add(Cell(nx, ny))
                            }
                        }
                    }
                    if (comp.size > bestComponent.size) {
                        bestComponent = comp
                    }
                }
            }
        }

        val out = Array(h) { BooleanArray(w) }
        for (c in bestComponent) {
            out[c.y][c.x] = true
        }

        // Fill enclosed 1-cell pinholes (cells surrounded by 4 filled orthogonal neighbors)
        for (y in 1 until h - 1) {
            for (x in 1 until w - 1) {
                if (!out[y][x] && out[y - 1][x] && out[y + 1][x] && out[y][x - 1] && out[y][x + 1]) {
                    out[y][x] = true
                }
            }
        }
        return out
    }

    fun isSingleConnectedComponent(cells: Set<Cell>): Boolean {
        if (cells.isEmpty()) return false
        val start = cells.first()
        val visited = HashSet<Cell>(cells.size)
        val queue = ArrayDeque<Cell>()
        queue.add(start)
        visited.add(start)
        while (queue.isNotEmpty()) {
            val cur = queue.removeFirst()
            for (dir in Direction.entries) {
                val next = cur.step(dir)
                if (next in cells && visited.add(next)) {
                    queue.add(next)
                }
            }
        }
        return visited.size == cells.size
    }
